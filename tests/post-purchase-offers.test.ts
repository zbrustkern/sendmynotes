import assert from "node:assert/strict";
import { withSafeTestHarness } from "../lib/testing/safe-harness";
import { firestoreDb, getOrdersCollection } from "../lib/firebase-admin";
import { ensureFollowupOffer, GRANTS } from "../lib/post-purchase/offers";
import { recordPostPurchaseAttribution, validateFollowupLinkForCheckout } from "../lib/post-purchase/attribution";
import { stripPrivateRetention } from "../lib/post-purchase/privacy";
import { getSenderKey } from "../lib/post-purchase/preferences";
import { issueOfferPriceQuote } from "../lib/offer-engine";
import type { Order } from "../lib/types";

async function main() {
 await withSafeTestHarness(async () => {
  process.env.POST_PURCHASE_SENDER_HMAC_KEY = "test-only-not-a-production-secret-123456";
  const input = { enrollmentId: "synthetic-enrollment", sourceOrderId: "synthetic-source", messageId: "synthetic-message", at: Date.now(), amountCents: 100, validDays: 60 };
  const grants = await Promise.all(Array.from({length: 8}, () => ensureFollowupOffer(input)));
  assert.equal(new Set(grants.map(x=>x.code)).size, 1, "concurrent issuance reuses one code");
  const grant = grants[0];
  assert.equal((await firestoreDb.collection(GRANTS).get()).size, 1);
  const retry = await ensureFollowupOffer({...input, at: input.at + 86400000, validDays: 1});
  assert.deepEqual(retry, grant, "retry cannot change coupon expiry or terms");
  await assert.rejects(ensureFollowupOffer({...input, amountCents: 900}));
  const quote = await issueOfferPriceQuote({code:grant.code,listPriceCents:900});
  assert.equal(quote.valid,true); assert.equal(quote.finalAmountInCents,800);
  assert.equal(quote.offer?.maxUses,1); assert.equal(quote.offer?.stackingAllowed,false);
  assert.equal(new URL(grant.offerUrl).pathname,"/new");
  assert.ok(!grant.offerUrl.includes(input.sourceOrderId));
  process.env.POST_PURCHASE_LINK_SECRET = "test-only-link-secret-123456789012345678";
  const {ensureFollowupLink,recordFollowupLinkObservation} = await import("../lib/post-purchase/links");
  const link = await ensureFollowupLink({messageId:"observed-message",enrollmentId:"observed-enrollment",sourceOrderId:"observed-source"});
  const observation = await recordFollowupLinkObservation(link.reference);
  assert.equal(await validateFollowupLinkForCheckout(observation,false),undefined,"analytics opt-out omits optional association");
  const verifiedLink=await validateFollowupLinkForCheckout(observation,true);
  assert.ok(verifiedLink);
  assert.ok(!JSON.stringify(verifiedLink).includes(link.reference),"raw reference never saved on order");
  const sourceKey=getSenderKey("synthetic@example.invalid");
  await getOrdersCollection().doc(input.sourceOrderId).set({id:input.sourceOrderId,postPurchaseSenderKey:sourceKey});
  const base = {id:"synthetic-repeat",customerEmail:"synthetic@example.invalid",discountCode:grant.code,attribution:{utmSource:"google"},postPurchaseLinkObservation:verifiedLink,purchaseMeasurement:{version:1,transactionId:"synthetic-repeat",amountInCents:800,currency:"USD",verifiedAt:Date.now(),eligible:true,reason:"eligible",refundStatus:"unknown"}} as Order;
  await getOrdersCollection().doc(base.id).set(base);
  await recordPostPurchaseAttribution(base);
  assert.equal((await getOrdersCollection().doc(base.id).get()).data()?.retentionAttribution?.method,"observed_link","verified purchase may have a link association, but quote is not redemption");
  await firestoreDb.collection("offer_redemptions").doc(`redemption_${base.id}`).set({offerId:grant.offerId});
  await Promise.all([recordPostPurchaseAttribution(base),recordPostPurchaseAttribution(base)]);
  const repeat=(await getOrdersCollection().doc(base.id).get()).data() as Order;
  assert.equal(repeat.retentionAttribution?.buyerAssociation,"observed_repeat");
  assert.equal(repeat.retentionAttribution?.method,"redeemed_code","redeemed code takes precedence over conflicting earlier link");
  assert.equal(repeat.postPurchaseLinkObservation?.sourceOrderId,"observed-source","original optional link observation retained separately");
  assert.equal(stripPrivateRetention(repeat).postPurchaseSenderKey,undefined);
  assert.equal(stripPrivateRetention(repeat).retentionAttribution,undefined);
  assert.deepEqual(repeat.attribution,base.attribution,"original Google evidence preserved");
  const other={...base,id:"synthetic-other",customerEmail:"other@example.invalid"};
  await getOrdersCollection().doc(other.id).set(other);
  await firestoreDb.collection("offer_redemptions").doc(`redemption_${other.id}`).set({offerId:grant.offerId});
  await recordPostPurchaseAttribution(other);
  assert.equal((await getOrdersCollection().doc(other.id).get()).data()?.retentionAttribution?.buyerAssociation,"different_email_possible_referral");
  const test={...base,id:"synthetic-test",isTest:true};
  await getOrdersCollection().doc(test.id).set(test); await recordPostPurchaseAttribution(test);
  assert.equal((await getOrdersCollection().doc(test.id).get()).data()?.postPurchaseSenderKey,undefined);
 });
 console.log("Post-purchase offer issuance and private attribution checks passed.");
}
main().catch(error=>{console.error(error);process.exitCode=1;});
